#!/usr/bin/env python3
"""Bake the Flying Toasters toaster sprite into a Swift source file.

Source artwork: the XPM sprites published in
https://github.com/torunar/flying-toasters-xscreensaver (MIT).

Emits Sources/ToasterFrames.swift containing a 15-colour palette (index 0 is
transparent) plus every animation frame packed at 4 bits per pixel and base64
encoded, so the app stays self-contained with no resource bundle.

    python3 Tools/BakeToasterFrames.py toaster.xpm > Sources/ToasterFrames.swift
"""
import base64
import re
import sys


def parse_xpm(path):
    src = open(path).read()
    frames = []
    for block in re.split(r'\{\s*"', src)[1:]:
        strings = re.findall(r'"([^"]*)"', '"' + block)
        header = strings[0].split()
        if len(header) < 4:
            continue
        w, h, ncolors, cpp = (int(v) for v in header[:4])
        colours = {}
        for line in strings[1:1 + ncolors]:
            key = line[:cpp]
            rest = line[cpp:].strip()
            m = re.search(r'#([0-9A-Fa-f]{6})', rest)
            colours[key] = None if 'None' in rest else m.group(1).upper()
        rows = strings[1 + ncolors:1 + ncolors + h]
        grid = []
        for y in range(h):
            row = rows[y] if y < len(rows) else ''
            grid.append([colours.get(row[x * cpp:(x + 1) * cpp]) for x in range(w)])
        frames.append((w, h, grid))
    return frames


def main():
    frames = parse_xpm(sys.argv[1])
    w, h, _ = frames[0]
    assert all(f[0] == w and f[1] == h for f in frames), 'frame sizes differ'

    # Index 0 is transparent; the rest are encountered in first-use order so the
    # palette stays stable across runs.
    palette = [None]
    index = {}
    packed = bytearray()

    for _, _, grid in frames:
        nibbles = []
        for row in grid:
            for colour in row:
                if colour is None:
                    nibbles.append(0)
                    continue
                if colour not in index:
                    index[colour] = len(palette)
                    palette.append(colour)
                nibbles.append(index[colour])
        assert len(palette) <= 16, f'{len(palette)} colours, need 4bpp'
        nibbles += [0] * (len(nibbles) % 2)
        for i in range(0, len(nibbles), 2):
            packed.append((nibbles[i] << 4) | nibbles[i + 1])

    payload = base64.b64encode(bytes(packed)).decode()
    lines = [payload[i:i + 96] for i in range(0, len(payload), 96)]

    def literal(colour):
        if colour is None:
            return '0x00000000'
        r, g, b = (int(colour[i:i + 2], 16) for i in (0, 2, 4))
        # Premultiplied, matching the renderer's blend state.
        return f'0xFF{r:02X}{g:02X}{b:02X}'

    out = []
    out.append('// Generated by Tools/BakeToasterFrames.py — do not edit by hand.')
    out.append('//')
    out.append('// Toaster animation frames baked from the XPM sprites published in')
    out.append('// https://github.com/torunar/flying-toasters-xscreensaver (MIT).')
    out.append('// Six frames of 64x64, 15 colours, packed at 4 bits per pixel.')
    out.append('')
    out.append('enum ToasterFrames {')
    out.append(f'    static let width = {w}')
    out.append(f'    static let height = {h}')
    out.append(f'    static let frameCount = {len(frames)}')
    out.append('')
    out.append('    /// 0xAARRGGBB, premultiplied. Index 0 is fully transparent.')
    out.append('    static let palette: [UInt32] = [')
    for i in range(0, len(palette), 4):
        chunk = ', '.join(literal(c) for c in palette[i:i + 4])
        out.append(f'        {chunk},')
    out.append('    ]')
    out.append('')
    out.append('    /// Frames concatenated, 4 bits per pixel, high nibble first.')
    out.append('    static let packedBase64 = """')
    out.append('\n'.join('        ' + line for line in lines))
    out.append('        """')
    out.append('}')
    print('\n'.join(out))


main()
